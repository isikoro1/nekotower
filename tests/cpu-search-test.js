const assert = require('node:assert/strict');
const Matter = require('../vendor/matter.min.js');
const Cpu = require('../src/cpu-player.js');
const platform = Matter.Bodies.rectangle(450, 930, 130, 30, {isStatic:true, friction:1});
const active = Matter.Bodies.rectangle(450, 150, 60, 180, {friction:.94,frictionStatic:1.6,frictionAir:.012,restitution:.01,density:.0018});
Matter.Body.setAngle(active,.3);
Matter.Body.setStatic(active,true);
const original = JSON.stringify([Cpu.describe(platform),Cpu.describe(active)]);
const snapshot = {bodies:[Cpu.describe(platform),Cpu.describe(active)],activeIndex:1,aimY:150,failY:1260,center:450,gravity:{x:0,y:.8,scale:.001}};
const beforeSnapshot=JSON.stringify(snapshot);
const unsafe = Cpu.evaluate(snapshot,{x:680,angle:0},Matter);
const safe = Cpu.evaluate(snapshot,{x:450,angle:Math.PI/2},Matter);
assert.equal(unsafe.failed,true,'Missed platform must be rejected');
assert.equal(safe.failed,false,'Flat centered cat should stay on platform');
const search = Cpu.createSearch(snapshot,Matter);
let last;
const start=performance.now();
while(search.index<search.total)last=search.next();
assert.ok(last.done);
assert.equal(last.best.failed,false);
assert.ok(last.best.score>=safe.score-1e-6);
assert.equal(JSON.stringify(snapshot),beforeSnapshot,'Candidate trials mutated shared snapshot');
assert.equal(JSON.stringify([Cpu.describe(platform),Cpu.describe(active)]),original,'Planner mutated real bodies');
// Compound hitboxes must also survive cloning and remain detached from live parts.
const compound=Matter.Body.create({parts:[Matter.Bodies.rectangle(430,150,50,60),Matter.Bodies.rectangle(470,180,65,45)]});
Matter.Body.setAngle(compound,.4);
Matter.Body.setStatic(compound,true);
const compoundBefore=JSON.stringify(Cpu.describe(compound));
const compoundSnapshot={...snapshot,bodies:[Cpu.describe(platform),Cpu.describe(compound)]};
const result=Cpu.evaluate(compoundSnapshot,{x:450,angle:0},Matter);
assert.ok(Number.isFinite(result.score));
assert.equal(JSON.stringify(Cpu.describe(compound)),compoundBefore);
console.log(JSON.stringify({ok:true,candidates:last.evaluated,best:last.best,searchMs:Math.round(performance.now()-start)}));
// Run the actual Worker entry point with its importScripts in an isolated VM.
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const messages=[];
let closed=false;
const workerContext={console,performance,postMessage:message=>messages.push(message),close:()=>{closed=true;}};
workerContext.self=workerContext;
vm.createContext(workerContext);
workerContext.importScripts=(...files)=>{
  for(const file of files)vm.runInContext(fs.readFileSync(path.resolve(__dirname,'../src',file.split('?')[0]),'utf8'),workerContext);
};
vm.runInContext(fs.readFileSync(path.join(__dirname,'../src/cpu-worker.js'),'utf8'),workerContext);
workerContext.onmessage({data:snapshot});
assert.ok(messages.length>1);
assert.equal(messages.at(-1).done,true);
assert.equal(messages.at(-1).best.failed,false);
assert.equal(closed,true);
console.log('CPU worker entry point passed');
